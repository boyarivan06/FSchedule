CREATE TABLE families (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR,
    admin_id BIGINT,
    CONSTRAINT families_admin_id_key
        FOREIGN KEY (admin_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE INDEX idx_families_admin_id ON families(admin_id);
ALTER TABLE children ADD COLUMN family_id BIGINT;
ALTER TABLE children ADD CONSTRAINT children_family_id_key FOREIGN KEY (family_id) REFERENCES families(id) ON DELETE CASCADE;
CREATE INDEX idx_children_family_id ON children(family_id);
